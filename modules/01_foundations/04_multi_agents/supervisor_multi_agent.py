from typing import Dict, Literal
from datetime import datetime
from langchain_core.messages import HumanMessage, AIMessage
from langchain_core.prompts import ChatPromptTemplate
from langchain_openai import ChatOpenAI
from langgraph.graph import END, StateGraph, MessagesState
from dotenv import load_dotenv


## Define the  State

class SupervisorState(MessagesState):
    """State for the supervisor agent, including messages and context."""
    next_agent: str ="" # which agent is currently active
    research_data:str = "" # date of the research
    analysis: str = "" # analysis of the research
    final_report: str = "" # final report generated by the supervisor
    task_complete: bool = False # flag to indicate if the task is complete
    current_task: str = "" # current task being performed by the agent


## define llm
def llm(model: str = "gpt-5", temperature: float = 0.7) -> ChatOpenAI:
    """Create an OpenAI model with the specified parameters."""
    return ChatOpenAI(model=model, temperature=temperature)


## create supervisor with openai llm
def create_supervisor_chain():
    """Create the supervisor decision chain with OpenAI LLM."""

    supervisor_prompt = ChatPromptTemplate.from_messages([
        ("system","""You are a supervior managing a team of AI Agents:

        1. Research Agent: Responsible for gathering information and data on the assigned topic.
        2. Analyst Agent: Responsible for analyzing the gathered information and providing insights.
        3. Writer Agent: Responsible for compiling the analysis into a comprehensive report.

        Based on teh current state and conversations, decide which agent should be called next and provide the necessary instructions for that agent.
        If the task is complee, responsd with 'DONE' and provide the final report.

        Current state:
        - Has research data : {has_research}
        - Has analysis : {has_analysis}
        - Has final report : {has_final_report}

        Response with ONLY the agent name (researcher/analyst/writer) or DONE"""),
        ("human","{task}")

    ])

    return supervisor_prompt | llm()


## Define supervisor agent
def create_supervisor_agent(state:SupervisorState) -> Dict:
    """Supervisor decides next agent usign openai LLM"""

    messages = state["messages"]
    task = state.get("current_task") or (messages[0].content if messages else "No task")

    ## check what has been completed

    has_research = bool(state.get("research_data",""))
    has_analysis = bool(state.get("analysis",""))
    has_final_report = bool(state.get("final_report"))

    # Get LLM Decision
    chain = create_supervisor_chain()
    decision = chain.invoke({
        "task":task,
        "has_research": has_research,
        "has_analysis": has_analysis,
        "has_final_report": has_final_report
    })

    ## Parse decision
    decision_text = decision.content.strip().lower()
    print(decision_text)

    if "done" in decision_text or has_final_report:
        next_agent = "end"
        supervisor_msg = "Supervisor: All task completed! Great work team."
    elif "researcher" in decision_text or not has_research:
        next_agent = "researcher"
        supervisor_msg = "Supervisor: Let's start with research. Assigning to Researcher..."
    elif "analyst" in decision_text or (has_research and not has_analysis):
        next_agent = "analyst"
        supervisor_msg = "Supervisor: Research done. Time for analysis. Assigning to Analyst..."
    elif "writter" in decision_text or (has_analysis and not has_final_report):
        next_agent = "writter"
        supervisor_msg = "Supervisor: Analysis completed. Create the report, Assigning to Writter ..."
    else:
        next_agent = "end"
        supervisor_msg = "Supervisor: Task completed"

    return {
        "messages":[AIMessage(content=supervisor_msg)],
        "next_agent":next_agent,
        "current_task":task
    }


### Researcher

def researcher_agent(state:SupervisorState) -> Dict:
    """Researcher uses OPENAI GPT model to gather information on the task"""

    task = state.get("current_task","")

    ## Create researcher prompt
    researcher_prompt = f"""As a professional research specialist, gather the key information needed for the task below.

Task: {task}

Write your findings in Markdown with these sections, each as a "## " heading:
1. Background
2. Key Facts
3. Current Trends & Developments
4. Statistics & Data Points
5. Examples & Case Studies

Use bullet points, and keep each point short and factual.
If you are unsure about a fact or figure, say so rather than guessing.
Do not add a title; start directly with the Background.
"""

    research_response = llm().invoke([HumanMessage(content=researcher_prompt)])
    research_data = research_response.content

    ## Create researcher message
    researcher_msg = f"""# Research Notes

**Topic:** {task}

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M")}

---

{research_data}

---

*Researcher done. Handing back to Supervisor...*
"""

    return {
        "messages":[AIMessage(content=researcher_msg, name="researcher")],
        "research_data":research_data,
        "next_agent":"supervisor"
    }


### Analyst

def analyst_agent(state:SupervisorState) -> Dict:
    """Analyst uses OPENAI GPT model to analyze the research data"""

    research_data = state.get("research_data","")
    task = state.get("current_task","")

    ## Create analyst prompt
    analyst_prompt = f"""As a professional analyst, analyze the research findings below for the task.

Task: {task}

Research Findings:
{research_data}

Write your analysis in Markdown with these sections, each as a "## " heading:
1. Key Insights
2. Patterns & Trends
3. Risks & Opportunities
4. Gaps & Open Questions
5. Implications

Use bullet points, and base every point on the research findings above.
If the research does not support a conclusion, say so rather than guessing.
Do not add a title; start directly with the Key Insights.
"""

    analysis_response = llm().invoke([HumanMessage(content=analyst_prompt)])
    analysis = analysis_response.content

    ## Create analyst message
    analyst_msg = f"""# Analysis Notes

**Topic:** {task}

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M")}

---

{analysis}

---

*Analyst done. Handing back to Supervisor...*
"""

    return {
        "messages":[AIMessage(content=analyst_msg, name="analyst")],
        "analysis":analysis,
        "next_agent":"supervisor"
    }


## writter agent

def writter_agent(state:SupervisorState) -> Dict:
    """Writter uses OPENAI GPT model to create final report"""

    research_data = state.get("research_data","")
    analysis = state.get("analysis","")
    task =  state.get("current_task","")

    ## Create writter prompt
    writter_prompt = f"""As a professional writer, create an executive report based on the information below.

Task: {task}

Research Findings:
{research_data}

Analysis:
{analysis}

Write the report in Markdown with these sections, each as a "## " heading:
1. Executive Summary
2. Key Findings
3. Analysis & Insights
4. Recommendations
5. Conclusion

Use short paragraphs and bullet points where they help.
Do not add a report title; start directly with the Executive Summary.
Keep it professional and concise.
"""

    report_response = llm().invoke([HumanMessage(content=writter_prompt)])
    report = report_response.content

    ## Create final report
    final_report = f"""# Final Report

**Topic:** {task}

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M")}

---

{report}

---

*Compiled by the Supervisor Multi-AI-Agent System (Researcher → Analyst → Writer)*
"""

    return {
        "messages":[AIMessage(content=final_report, name="writer")],
        "final_report":final_report,
        "next_agent":"supervisor"
    }


## router function

def router(state:SupervisorState) -> Literal["supervisor","researcher","analyst","writter","__end__"]:
    """Route to the next node based on next_agent in the state"""

    next_agent = state.get("next_agent","supervisor")

    ## Stop when the supervisor says end or the report is done
    if next_agent == "end" or state.get("task_complete",False):
        return END

    ## Send to the agent the supervisor picked (or back to supervisor)
    if next_agent in ["supervisor","researcher","analyst","writter"]:
        return next_agent

    ## Anything unexpected goes back to the supervisor
    return "supervisor"


## create workflow
def supervisor_multi_agent_system():
    """Supervisor multi-agent system: supervisor routes work to researcher, analyst and writter"""

    # Create workflow
    workflow = StateGraph(SupervisorState)

    # Add nodes
    workflow.add_node("supervisor", create_supervisor_agent)
    workflow.add_node("researcher", researcher_agent)
    workflow.add_node("analyst", analyst_agent)
    workflow.add_node("writter", writter_agent)

    # Set entry point
    workflow.set_entry_point("supervisor")

    # Add routing
    for node in ["supervisor", "researcher", "analyst", "writter"]:
        workflow.add_conditional_edges(
            node,
            router,
            {
                "supervisor": "supervisor",
                "researcher": "researcher",
                "analyst": "analyst",
                "writter": "writter",
                END: END
            }
        )

    print("Compiled workflow successfully")
    return workflow.compile()


# LangGraph Studio entry point
load_dotenv()
graph = supervisor_multi_agent_system()


if __name__ == "__main__":
    print("Supervisor Multi-AI-Agent System (type 'exit', 'quit' or 'end' to stop)")

    while True:
        ## Get the query from the terminal
        user_input = input("\nYou: ").strip()

        ## End option
        if user_input.lower() in ["exit", "quit", "end"]:
            print("Goodbye!")
            break

        ## Skip empty input
        if not user_input:
            continue

        ## Call the supervisor multi-agent system with the user query
        result = graph.invoke(
            {"messages": [HumanMessage(content=user_input)]},
            config={"recursion_limit": 15}
        )

        ## Show the full conversation: supervisor decisions, research notes, analysis notes
        for message in result["messages"]:
            message.pretty_print()

        ## Show the final report
        print(result.get("final_report") or "No final report generated")
